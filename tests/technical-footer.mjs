import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {technicalPanel} from '../src/revision-stamp.js';
import {mountTechnicalFooter} from '../src/technical-footer.js';
const dom=new JSDOM('<main><section>'+technicalPanel('<p>r260</p>')+'<button>Read</button><article class="goe-card">'+technicalPanel('<p>Card r3</p>')+'<p>Story</p></article></section></main><footer>'+technicalPanel('<p>Reader v164</p>')+'</footer>');
for(const k of ['document','MutationObserver'])globalThis[k]=dom.window[k];
const main=document.querySelector('main'),footer=document.querySelector('footer');
const stop=mountTechnicalFooter(main,footer);
assert.equal(main.lastElementChild.dataset.pageTechnical,'');assert(!main.lastElementChild.open);
assert(main.lastElementChild.textContent.includes('r260'));assert(main.lastElementChild.textContent.includes('v164'));
assert.equal(footer.querySelectorAll('details').length,0);
assert.equal(document.querySelector('.goe-card').lastElementChild.tagName,'DETAILS');
