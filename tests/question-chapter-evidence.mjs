import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {questionChapterEvidence,questionChapterEvidenceHTML} from '../src/question-chapter-evidence.js';
const q={id:'question',title:'An open question',sourceChapterId:'ch1',sourceChapterRevision:4,sourceParagraph:3};
const chapters=[{id:'ch1',title:'Current saved title',chapter_number:6,revision:4,body:'Unchanged manuscript'}];
const original=structuredClone(q),source=structuredClone(chapters);
assert.equal(questionChapterEvidence(q,chapters).state,'Saved chapter revision matches');
const doc=new JSDOM(questionChapterEvidenceHTML(q,chapters,{chapterLink:n=>'#chapter='+n})).window.document;
assert.equal(doc.querySelector('[data-question-chapter] a').getAttribute('href'),'#chapter=6');
assert.match(doc.body.textContent,/Saved revision: 4/);
assert.match(doc.body.textContent,/Current revision: 4/);
assert.match(doc.body.textContent,/not automatic approval/);
assert.equal(questionChapterEvidence(q,[{...chapters[0],revision:5}]).state,'Linked chapter revision changed');
assert.equal(questionChapterEvidence(q,[]).state,'Linked chapter unavailable');
assert.equal(questionChapterEvidence({id:'none'},chapters).state,'No saved chapter linked');
assert.equal(questionChapterEvidence({id:'noRevision',sourceChapterId:'ch1'},chapters).state,'No source revision recorded');
const retired=[{...chapters[0],recordStatus:'superseded'}];
assert.equal(questionChapterEvidence(q,retired).state,'Linked chapter unavailable');
const unsafe=new JSDOM(questionChapterEvidenceHTML(q,[{...chapters[0],title:'<script>bad()</script>'}])).window.document;
assert.equal(unsafe.querySelectorAll('script').length,0);
assert.deepEqual(q,original);
assert.deepEqual(chapters,source);
console.log('PASS question linked chapter ID, current revision, missing and retired sources, links, HTML escape and unchanged manuscript');
