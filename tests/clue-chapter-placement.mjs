import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {makeToolProposal,storeToolProposal,reviewToolProposal} from '../src/source-tools.js';
import {clueAudit,clueReviewEvidence,clueReviewState,reviewClue} from '../src/clue-audit.js';
import {sourceToolsUI} from '../src/source-tools-ui.js';
const base={events:[{id:'c',title:'A secret',type:'clue',status:'proposal'},{id:'s',title:'The setup event',order:1},{id:'r',title:'The reveal event',order:9}],characters:[],workshop:{questions:[]},summary:'Unchanged'};
const chapters=[{id:'ch1',title:'First chapter',chapter_number:1,revision:2},{id:'ch2',title:'Second chapter',chapter_number:2,revision:3}];
const ctx={bookId:'book',branchId:'branch',baseRevision:8,writer:'Benji'};
const input={...ctx,kind:'clue',targetId:'c',author:'Benji',reason:'Record an explicitly planned setup and reveal',sourceRefs:[{kind:'events',id:'c'}],values:{type:'clue',setupEventId:'s',revealEventId:'r',setupChapterId:'ch2',revealChapterId:'ch1'}};
const old=structuredClone(base);
const proposal=makeToolProposal(base,input,ctx,chapters);
assert(proposal.sources.some(r=>r.kind==='chapters'&&r.id==='ch1'&&r.revision===2));
assert(proposal.sources.some(r=>r.kind==='chapters'&&r.id==='ch2'&&r.revision===3));
assert(proposal.sources.some(r=>r.kind==='events'&&r.id==='s'));
assert(proposal.sources.some(r=>r.kind==='events'&&r.id==='r'));
assert.deepEqual(base,old);
assert.throws(()=>makeToolProposal(base,{...input,values:{...input.values,revealChapterId:'missing'}},ctx,chapters),/available saved chapter/);
const pending=storeToolProposal(base,proposal);
const accepted=reviewToolProposal(pending,proposal.id,'approved',ctx,chapters,'Chapter placement is a plan, not prose confirmation');
assert.deepEqual(base,old);
assert(accepted.events[0].setupChapterId==='ch2');
assert(accepted.events[0].revealChapterId==='ch1');
const audited=clueAudit(accepted,chapters);
assert(audited.rows[0].notices.some(n=>n.code==='planned-chapter-order'));
const reviewed=reviewClue(accepted,{eventId:'c',decision:'unchanged',note:'The reversed order is deliberate',expected:clueReviewEvidence(accepted,'c',chapters)},{bookId:'book',branchId:'branch',sourceRevision:9,writer:'Benji'},chapters);
assert.equal(clueReviewState(reviewed,'c',chapters).stale,false);
assert.equal(clueReviewState(reviewed,'c',chapters.map(x=>x.id==='ch1'?{...x,revision:4}:x)).stale,true);
let data=structuredClone(accepted);
const c={model:()=>data,bookId:'book',branch:()=>({id:'branch',revision:9}),chapters:()=>chapters,writer:()=> 'Benji',route:()=> '#source',chapterLink:num=>'#chapter='+num,select:(n,l)=>'<select name="'+n+'"></select>',field:n=>'<input name="'+n+'">'};
const ui=sourceToolsUI(c);
const html=new JSDOM(ui.cluesHTML()).window.document;
assert.match(html.body.textContent,/Setup chapter \(planned, not evidence in saved prose\)/);
assert.match(html.body.textContent,/Second chapter/);
assert.match(html.body.textContent,/First chapter/);
assert.match(html.body.textContent,/No saved chapter linked/);
chapters[1].title='Renamed second chapter';
assert.match(new JSDOM(ui.cluesHTML()).window.document.body.textContent,/Renamed second chapter/);
assert.deepEqual(base,old);
console.log('PASS separate planned setup/reveal chapter and event IDs, source snapshots, reversible approval, order audit, renamed labels and unchanged manuscript');
