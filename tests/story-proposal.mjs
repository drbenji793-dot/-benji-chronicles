import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
import {currentStoryUI,storySource} from '../src/current-story.js';
const draft=JSON.parse(fs.readFileSync('editorial/ibn-r152-proposal.json','utf8'));
const eventIds=[...new Set(draft.chapters.flatMap(c=>c.eventIds))];
const questionIds=[...new Set(draft.chapters.flatMap(c=>c.questionIds))];
assert.equal(eventIds.length,31);assert.equal(questionIds.length,121);
assert.equal(draft.chapters.length,41);
assert(draft.chapters.every(c=>c.points.length>=3&&c.summary&&c.turn&&c.next&&c.characters&&c.location&&c.timing));
const data={events:eventIds.map((id,i)=>({id,title:'حدث '+i})),workshop:{questions:questionIds.map((id,i)=>({id,title:'سؤال '+i,answer:'محفوظ'}))}};
draft.source=storySource(data);data.storyDraft=draft;
const original=JSON.stringify(data);
const dom=new JSDOM('<main></main>');const root=dom.window.document.querySelector('main');
const old={id:'old',version:1,status:'approved',synopsis:'النسخة السابقة',treatment:'قراءة سابقة',chapters:[],source:draft.source};
let ui;const render=()=>{root.innerHTML=ui.html();ui.bind(root)};
ui=currentStoryUI({model:()=>data,project:()=>({published:{data:{currentStory:old}}}),route:(v,p)=>'#'+new URLSearchParams(p),render});
render();assert(root.textContent.includes('مسودة جديدة للمراجعة'));
root.querySelector('[data-story-tab=chapters]').click();
assert.equal(root.querySelectorAll('.current-chapter').length,41);
assert.equal(root.querySelectorAll('.current-chapter > button[data-story-feedback]').length,41);
assert.equal(root.querySelectorAll('.current-chapter > details').length,41);
assert(root.textContent.includes('31 من 31'));
assert([...root.querySelectorAll('a')].some(a=>a.getAttribute('href').includes('focuskind=question')));
root.querySelector('[data-story-edition=current]').click();
root.querySelector('[data-story-tab=synopsis]').click();assert(root.textContent.includes('النسخة السابقة'));
root.querySelector('[data-story-edition=draft]').click();root.querySelector('[data-story-tab=story]').click();
assert.equal(root.querySelectorAll('.current-prose').length,1);assert.equal(root.querySelectorAll('[data-story-page] option').length,41);
root.querySelector('[data-story-step="1"]').click();assert(root.querySelector('.current-prose details'));
data.events.push({id:'unplaced',title:'حدث جديد لم يوزع'});root.querySelector('[data-story-tab=chapters]').click();
assert(root.textContent.includes('أحداث لم تُوزع بعد: 1'));data.events.pop();
assert.equal(JSON.stringify(data),original);
console.log('PASS 41 chapter cards, 31 event and 121 question links, draft/current isolation, paging, notes, unassigned-event detection, no data mutation');
dom.window.close();
