import assert from 'node:assert/strict';
import {clueKnowledgeTimingNotices} from '../src/clue-knowledge-timing.js';
import {clueAudit} from '../src/clue-audit.js';
const hero={id:'hero',name:'Hero'};
const fact={id:'fact',type:'secret',title:'The secret',order:1};
const clue={id:'scene',type:'clue',title:'Action',order:4,truth:'True',setup:'Recorded',revealEventId:'reveal',
 requiredKnowledge:[{characterId:'hero',factEventId:'fact'}]};
const reveal={id:'reveal',order:9,title:'Reveal'};
const lateAcquisition={id:'late',order:7,knowledgeRecords:[{id:'k1',eventId:'late',factEventId:'fact',characterId:'hero',readingOrder:7,state:'knows',status:'approved'}]};
const base={characters:[hero],events:[fact,clue,reveal,lateAcquisition],workshop:{questions:[]}};
const original=structuredClone(base);
const notices=clueKnowledgeTimingNotices(base,clue);
assert(notices.some(n=>n.code==='required-knowledge-late:hero:fact'));
assert(!notices.some(n=>n.code==='required-knowledge-not-recorded:hero:fact'));
const early=structuredClone(base);
early.events.push({id:'early',order:2,knowledgeRecords:[{id:'k2',characterId:'hero',factEventId:'fact',state:'knows',status:'approved',readingOrder:2}]});
assert(!clueKnowledgeTimingNotices(early,clue).some(n=>n.code.startsWith('required-knowledge-late')));
const absent=structuredClone(base);absent.events=absent.events.filter(e=>e.id!=='late');
assert(clueKnowledgeTimingNotices(absent,clue).some(n=>n.code==='required-knowledge-not-recorded:hero:fact'));
const unknown=structuredClone(base);unknown.events.find(e=>e.id==='late').order=null;unknown.events.find(e=>e.id==='late').knowledgeRecords[0].readingOrder=null;
assert(clueKnowledgeTimingNotices(unknown,clue).some(n=>n.code.startsWith('required-knowledge-time-unknown')));
assert(!clueKnowledgeTimingNotices(unknown,clue).some(n=>n.code.startsWith('required-knowledge-late')));
const unread=structuredClone(base);unread.events.find(e=>e.id==='late').knowledgeRecords[0].state='possesses_unread';
assert(clueKnowledgeTimingNotices(unread,clue).some(n=>n.code.startsWith('required-knowledge-not-recorded')));
const overdue=structuredClone(base);overdue.events.find(e=>e.id==='scene').knowledgeRecords=[{id:'k3',readingOrder:8,state:'knows',status:'approved'}];
assert(clueKnowledgeTimingNotices(overdue,overdue.events[1]).some(n=>n.code==='knowledge-after-event:k3'));
assert(clueAudit(base).rows.find(r=>r.event.id==='scene').notices.some(n=>n.code.startsWith('required-knowledge-late')));
assert.deepEqual(base,original);
console.log('PASS explicit knowledge requirements, later and unknown acquisitions, unread evidence distinction, no inferred plot facts or content changes');
