import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
import {currentStoryUI,storyPages,storySource} from '../src/current-story.js';
const draft=JSON.parse(fs.readFileSync('editorial/ibn-r152-proposal.json','utf8'));
const chapters=JSON.stringify(draft.chapters);
draft.treatment=fs.readFileSync('editorial/ibn-connected-treatment.txt','utf8');
draft.sectionNotes={};
assert.equal(storyPages(draft).length,14);
assert.equal(JSON.stringify(draft.chapters),chapters);
assert(!draft.chapters.some(c=>draft.treatment.includes(c.summary)));
const data={events:[],storyDraft:draft};draft.source=storySource(data);
const before=JSON.stringify(data);
const dom=new JSDOM('<main></main>'),root=dom.window.document.querySelector('main');
let ui;const render=()=>{root.innerHTML=ui.html();ui.bind(root)};
ui=currentStoryUI({model:()=>data,project:()=>({published:{data:{currentStory:{id:'old',treatment:'قديم',chapters:[],synopsis:'قديم',source:draft.source}}}}),route:()=> '#',render});
render();
assert(root.querySelector('.current-story-entry').textContent.includes('اقرأ الحكاية متصلة'));
root.querySelector('.current-story-entry').click();
assert.equal(root.querySelectorAll('[data-story-page] option').length,14);
assert(!root.querySelector('.current-prose').textContent.includes('---'));
assert(root.querySelector('.current-prose').textContent.includes('قبل أن يعرف الناس'));
root.querySelector('.current-bottom-pager [data-story-step="1"]').click();
assert(root.querySelector('.current-prose').textContent.includes('الثمن الذي يقبله الصديق'));
root.querySelector('[data-story-tab=chapters]').click();
assert.equal(root.querySelectorAll('.current-chapter').length,41);
assert.equal(JSON.stringify(data),before);
dom.window.close();
console.log('PASS independent 14 reading sections, 41 intact chapter cards, visible entry, bottom navigation, no mutation');
